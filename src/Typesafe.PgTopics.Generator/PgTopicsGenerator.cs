using System.Collections.Immutable;
using System.Reflection;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Typesafe.PgTopics.Generator;

// Adds the Typesafe.PgTopics runtime (Runtime/*.cs, embedded in this DLL) to the project as source code. Shipping
// source instead of a compiled library means it compiles against the app's own Npgsql version and target framework,
// with no binary dependency to keep in sync, and students can read and step into it like their own code.
// The runtime needs Npgsql; without it the generator reports PGTOPICS001 instead of producing code that doesn't
// compile. AddPostgresTopics is only added when the project has Microsoft.Extensions.DependencyInjection, and the
// gRPC live-query helper only when it has Grpc.Core.Api.
[Generator]
public sealed class PgTopicsGenerator : IIncrementalGenerator
{
    private const string ResourcePrefix = "Runtime/";
    private const string DependencyInjectionFile = "ServiceCollectionExtensions.cs";
    private const string GrpcFile = "GrpcLiveQueryExtensions.cs";

    private static readonly DiagnosticDescriptor MissingNpgsql = new(
        "PGTOPICS001",
        "Npgsql is missing",
        "Typesafe.PgTopics needs Npgsql: add <PackageReference Include=\"Npgsql\" Version=\"...\" /> to the project",
        "Configuration",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly ImmutableArray<(string File, string Text)> Runtime = LoadRuntime();

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var references = context.CompilationProvider.Select(static (compilation, _) => (
            Npgsql: compilation.GetTypeByMetadataName("Npgsql.NpgsqlDataSource") is not null,
            DependencyInjection: compilation.GetTypeByMetadataName(
                "Microsoft.Extensions.DependencyInjection.IServiceCollection") is not null,
            Grpc: compilation.GetTypeByMetadataName("Grpc.Core.IServerStreamWriter`1") is not null));

        context.RegisterSourceOutput(references, static (context, found) =>
        {
            if (!found.Npgsql)
            {
                context.ReportDiagnostic(Diagnostic.Create(MissingNpgsql, Location.None));
                return;
            }

            foreach (var (file, text) in Runtime)
            {
                if (file == DependencyInjectionFile && !found.DependencyInjection)
                    continue;
                if (file == GrpcFile && !found.Grpc)
                    continue;

                var source = "// <auto-generated by Typesafe.PgTopics (https://github.com/uldahlalex/Typesafe.PgTopics) />\n"
                    + "#nullable enable\n"
                    + text;
                context.AddSource($"Typesafe.PgTopics.{Path.GetFileNameWithoutExtension(file)}.g.cs",
                    SourceText.From(source, Encoding.UTF8));
            }
        });
    }

    private static ImmutableArray<(string File, string Text)> LoadRuntime()
    {
        var assembly = typeof(PgTopicsGenerator).Assembly;
        return assembly.GetManifestResourceNames()
            .Where(static name => name.StartsWith(ResourcePrefix, StringComparison.Ordinal))
            .OrderBy(static name => name, StringComparer.Ordinal)
            .Select(name =>
            {
                using var reader = new StreamReader(assembly.GetManifestResourceStream(name)!);
                return (name.Substring(ResourcePrefix.Length), reader.ReadToEnd());
            })
            .ToImmutableArray();
    }
}
